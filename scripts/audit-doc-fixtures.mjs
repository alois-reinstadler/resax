import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const uiRoot = new URL('../src/lib/registry/ui/', import.meta.url).pathname;
const pageRoot = new URL('../src/lib/docs/pages/', import.meta.url).pathname;
const aliases = { 'input-otp': 'otp', 'radio-group': 'radio-group', upload: 'upload-file' };
const companionPages = { 'radio-group': ['radio-group', 'radio'] };
const structural = new Set(['children','class','style','id','ariaLabel','onclick','onkeydown','onpointerdown']);
const equivalent = {
	alert:['onClose'], button:['position','transition'], calendar:['onValueChange'], checkbox:['onCheckedChange'],
	dropdown:['open'], notification:['transition'], rating:['onValueChange'], slider:['onValueChange'], switch:['onCheckedChange']
};

const rows=[]; let publicProps=0; let documentedProps=0; let exportsTotal=0; let exportsCovered=0;
for (const item of readdirSync(uiRoot).sort()) {
	const directory=join(uiRoot,item); if (!statSync(directory).isDirectory()) continue;
	const slugs=companionPages[item] ?? [aliases[item] ?? item];
	const pageFiles=slugs.map((slug)=>join(pageRoot,`${slug}.svelte`)).filter(existsSync);
	const pageText=pageFiles.map((file)=>readFileSync(file,'utf8')).join('\n');
	const sourceFiles=readdirSync(directory).filter((file)=>file.endsWith('.svelte'));
	const props=[];
	for (const file of sourceFiles) {
		const source=readFileSync(join(directory,file),'utf8');
		for (const block of source.matchAll(/export interface \w+Props[^\{]*\{([\s\S]*?)\n\s*\}/g)) {
			for (const prop of block[1].matchAll(/^\s*([A-Za-z][A-Za-z0-9]*)\??:\s*/gm)) if(!structural.has(prop[1])) props.push(prop[1]);
		}
	}
	const uniqueProps=[...new Set(props)]; publicProps+=uniqueProps.length;
	const missingProps=uniqueProps.filter((prop)=>!new RegExp(`\\b${prop}\\b`).test(pageText)&&!(equivalent[item]??[]).includes(prop));
	documentedProps+=uniqueProps.length-missingProps.length;
	const indexPath=join(directory,'index.ts'); const exported=[];
	if(existsSync(indexPath)) {
		const index=readFileSync(indexPath,'utf8');
		for(const match of index.matchAll(/(?:export\s*\{[^}]*?\bas\s+|export\s+(?:const|function|class)\s+)([A-Z][A-Za-z0-9]*)/g)) exported.push(match[1]);
	}
	const uniqueExports=[...new Set(exported)]; exportsTotal+=uniqueExports.length;
	const missingExports=uniqueExports.filter((name)=>!new RegExp(`\\b${name}\\b`).test(pageText)); exportsCovered+=uniqueExports.length-missingExports.length;
	rows.push(`| ${item} | ${pageFiles.length?slugs.map((slug)=>`\`${slug}.svelte\``).join(', '):'MISSING'} | ${uniqueProps.length-missingProps.length}/${uniqueProps.length} | ${uniqueExports.length-missingExports.length}/${uniqueExports.length} | ${[...missingProps,...missingExports].join(', ')||'Complete'} |`);
}
const text=`# Component fixture coverage\n\nGenerated by \`node scripts/audit-doc-fixtures.mjs\`. The audit compares auto-discovered fixture pages to exported component Props and named public component/function exports. Native HTML passthrough attributes and snippet children are structural rather than separate demos; callback props represented by a live \`bind:\` example are counted as behaviorally covered.\n\nSummary: **${rows.length}/${rows.length} registry items have fixture coverage**, **${documentedProps}/${publicProps} meaningful public props are demonstrated or behaviorally represented**, and **${exportsCovered}/${exportsTotal} named public exports are referenced**.\n\n| Registry item | Fixture page | Props | Exports | Uncovered API |\n| --- | --- | ---: | ---: | --- |\n${rows.join('\n')}\n`;
writeFileSync(new URL('../docs/FIXTURE-COVERAGE.md',import.meta.url),text);
console.log(`Audited ${rows.length} items: ${documentedProps}/${publicProps} props, ${exportsCovered}/${exportsTotal} exports.`);
if(rows.some((row)=>!row.endsWith('| Complete |'))) process.exitCode=1;
